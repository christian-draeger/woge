import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = new URL("../../../", import.meta.url);
const shared = new URL("examples/reference-application/shared/", root);
const work = new URL("../build/reference-theme/", import.meta.url);
const output = new URL("build/generated/theme-assets/static/assets/operations-tailwind.css", shared);
await mkdir(work, { recursive: true });
await mkdir(new URL("./", output), { recursive: true });
const source = await readFile(new URL("src/main/tailwind/operations.css", shared), "utf8");
const input = new URL("input.css", work);
await writeFile(input, source.replace('@source "../kotlin";',
  `@source "${fileURLToPath(new URL("src/main/kotlin", shared))}";`));
const compiler = spawnSync(process.execPath, [
  fileURLToPath(new URL("../node_modules/@tailwindcss/cli/dist/index.mjs", import.meta.url)),
  "-i", fileURLToPath(input), "-o", fileURLToPath(output), "--minify",
], { encoding: "utf8" });
if (compiler.status !== 0) throw new Error(`Reference Tailwind build failed: ${compiler.stderr}`);
const css = await readFile(output, "utf8");
for (const token of [".flex{", ".flex-wrap{", ".gap-4{", '[data-theme=tailwind]']) {
  if (!css.includes(token)) throw new Error(`Reference theme lost ${token}`);
}
console.log(`[woge-reference-theme] ${Buffer.byteLength(css)} reproducibly generated bytes`);
