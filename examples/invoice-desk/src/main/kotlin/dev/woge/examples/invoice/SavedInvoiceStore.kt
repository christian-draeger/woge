package dev.woge.examples.invoice

import java.math.BigDecimal
import java.sql.DriverManager
import java.sql.PreparedStatement
import java.sql.ResultSet
import java.sql.Statement
import java.time.LocalDate
import java.time.OffsetDateTime
import java.time.ZoneOffset

internal const val MAX_INVOICE_PRECISION = 18
internal const val MAX_RECEIPT_BYTES = 2048
internal const val INVOICE_PAGE_SIZE = 2

internal data class InvoiceAllocations(
    val first: BigDecimal,
    val second: BigDecimal,
)

internal data class InvoiceDraft(
    val values: InvoiceValues,
    val services: InvoiceAllocations,
    val materials: InvoiceAllocations,
)

internal data class SavedInvoice(
    val id: Long,
    val revision: Long,
    val draft: InvoiceDraft,
    val receiptBytes: Int,
)

/** An embedded, application-owned store for this fixed two-line example. */
internal class SavedInvoiceStore(
    private val url: String,
) {
    init {
        connect().use { connection ->
            connection.createStatement().use { statement ->
                statement.executeUpdate(
                    """
                    CREATE TABLE IF NOT EXISTS invoice_record (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        revision BIGINT NOT NULL DEFAULT 1,
                        amount DECIMAL(18,2) NOT NULL,
                        service_day DATE NOT NULL,
                        due_day DATE NOT NULL,
                        payment_instant TIMESTAMP WITH TIME ZONE NOT NULL,
                        services_first DECIMAL(18,2) NOT NULL,
                        services_second DECIMAL(18,2) NOT NULL,
                        materials_first DECIMAL(18,2) NOT NULL,
                        materials_second DECIMAL(18,2) NOT NULL,
                        receipt VARBINARY(2048) NOT NULL
                    )
                    """.trimIndent(),
                )
            }
        }
    }

    fun find(id: Long): SavedInvoice? =
        connect().use { connection ->
            connection.prepareStatement("$INVOICE_SELECT WHERE id=?").use { query ->
                query.setLong(1, id)
                query.executeQuery().use(::firstInvoice)
            }
        }

    fun page(number: Int): List<SavedInvoice> =
        connect().use { connection ->
            connection.prepareStatement("$INVOICE_SELECT ORDER BY id LIMIT ? OFFSET ?").use { query ->
                query.setInt(1, INVOICE_PAGE_SIZE + 1)
                query.setLong(2, (number - 1L) * INVOICE_PAGE_SIZE)
                query.executeQuery().use { result -> buildList { while (result.next()) add(result.invoice()) } }
            }
        }

    fun create(
        draft: InvoiceDraft,
        receipt: ByteArray,
    ): Long =
        connect().use { connection ->
            val sql = "INSERT INTO invoice_record ($INVOICE_COLUMNS,receipt) VALUES (?,?,?,?,?,?,?,?,?)"
            connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS).use { write ->
                write.bind(draft, receipt)
                check(write.executeUpdate() == 1)
                write.generatedKeys.use { keys ->
                    check(keys.next())
                    keys.getLong(1)
                }
            }
        }

    fun edit(
        id: Long,
        revision: Long,
        draft: InvoiceDraft,
        receipt: ByteArray?,
    ): Boolean =
        connect().use { connection ->
            val fields = INVOICE_COLUMNS.split(',').joinToString(",") { "$it=?" }
            val sql =
                "UPDATE invoice_record SET $fields,receipt=COALESCE(?,receipt),revision=revision+1 " +
                    "WHERE id=? AND revision=?"
            connection.prepareStatement(sql).use { write ->
                val identity = write.bind(draft, receipt)
                write.setLong(identity, id)
                write.setLong(identity + 1, revision)
                write.executeUpdate() == 1
            }
        }

    private fun connect() = DriverManager.getConnection(url)
}

private const val INVOICE_COLUMNS =
    "amount,service_day,due_day,payment_instant,services_first,services_second,materials_first,materials_second"
private const val INVOICE_SELECT =
    "SELECT id,revision,$INVOICE_COLUMNS,OCTET_LENGTH(receipt) AS receipt_bytes " +
        "FROM invoice_record"

private fun PreparedStatement.bind(
    draft: InvoiceDraft,
    receipt: ByteArray?,
): Int {
    var index = 1
    setBigDecimal(index++, draft.values.amount)
    setObject(index++, draft.values.serviceDay)
    setObject(index++, draft.values.dueDay)
    setObject(index++, draft.values.payment.atOffset(ZoneOffset.UTC))
    setBigDecimal(index++, draft.services.first)
    setBigDecimal(index++, draft.services.second)
    setBigDecimal(index++, draft.materials.first)
    setBigDecimal(index++, draft.materials.second)
    setBytes(index++, receipt)
    return index
}

private fun firstInvoice(result: ResultSet): SavedInvoice? = if (result.next()) result.invoice() else null

private fun ResultSet.invoice() =
    SavedInvoice(
        id = getLong("id"),
        revision = getLong("revision"),
        draft =
            InvoiceDraft(
                InvoiceValues(
                    getBigDecimal("amount"),
                    getObject("service_day", LocalDate::class.java),
                    getObject("due_day", LocalDate::class.java),
                    getObject("payment_instant", OffsetDateTime::class.java).toInstant(),
                ),
                InvoiceAllocations(getBigDecimal("services_first"), getBigDecimal("services_second")),
                InvoiceAllocations(getBigDecimal("materials_first"), getBigDecimal("materials_second")),
            ),
        receiptBytes = getInt("receipt_bytes"),
    )
